#!/usr/bin/env bash
# guard.sh — UserPromptSubmit-хук: детерминированно впрыскивает стандарты по типу задачи.
# Зачем: правила в промптах выветриваются из контекста, хук срабатывает КАЖДЫЙ раз.
# Подключение (~/.claude/settings.json):
#   "hooks": { "UserPromptSubmit": [ { "hooks": [ { "type": "command", "command": "~/.claude/hooks/guard.sh" } ] } ] }
# Адаптируй регулярки и тексты под свои типы задач — это шаблон, а не догма.

input="$(cat)"

# --- ЦИФРЫ / АНАЛИЗ ---
if printf '%s' "$input" | grep -Eiq 'анализ|сравни|конверси|провер.{0,20}(данн|метрик|цифр)|посчитай'; then
  echo '[guard] ЦИФРЫ: (1) агрегат по назначаемой группе (сегмент/пул/статус) разбить на до/после назначения; (2) каждое число наружу — проверено до механизма; (3) проверенное отделить от предположенного явно.'
fi

# --- ВЫГРУЗКА ЗАКАЗЧИКУ ---
if printf '%s' "$input" | grep -Eiq '(выгрузк|выгрузи|excel|csv).{0,40}(заказчик|коллег|отправ)|подготовь.{0,20}(файл|табличк)'; then
  echo '[guard] ВЫГРУЗКА: исключить тестовые записи (проверить пересечение = 0); человекочитаемые заголовки; лист-описание полей; прогнать чек-скрипт перед отправкой.'
fi

# --- ДОКУМЕНТАЦИЯ ---
if printf '%s' "$input" | grep -Eiq '(напиш|обнов|состав).{0,25}(доку|вики|readme|инструкци)'; then
  echo '[guard] ДОКА: вывод сверху (BLUF); все числа сверить с продом перед публикацией; дата актуализации.'
fi

exit 0
